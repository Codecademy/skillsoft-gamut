/* eslint-disable no-console -- CLI script; the console is its output. */
/*
 * gamut's own brands → src/tokens/generated/<brand>/, one folder per brand,
 * through the same API a team building its own brand uses
 * (@skillsoft/gamut-brand).
 *
 *   yarn workspace @skillsoft/gamut-styles build:tokens
 *   yarn workspace @skillsoft/gamut-styles build:tokens --check
 *
 * Output is checked in, so the theme and the package build don't need the
 * generator, culori or Style Dictionary. `--check` writes nothing and exits 1
 * if anything is out of date; a test runs it in CI.
 *
 * It imports @skillsoft/gamut-brand from source, not the package, so it
 * never needs a build first.
 */
import { readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { join, relative } from 'node:path';

import {
  BRANDS,
  DEFAULT_BRAND,
  staleFiles,
  writeBrand,
} from '../../gamut-brand/src';

const OUT = join(__dirname, '../src/tokens/generated');

/* The brands as namespaces: `brands.originalCodecademy.palette`, … */
const index = [
  '/* Generated by scripts/build-tokens.ts. Do not edit. */',
  ...BRANDS.map(({ name }) => `export * as ${name} from './${name}/values';`),
  '',
].join('\n');

const check = async () => {
  const stale = (
    await Promise.all(BRANDS.map((b) => staleFiles(b, join(OUT, b.name))))
  ).flat();
  const current = await readFile(join(OUT, 'index.ts'), 'utf8').catch(
    () => undefined
  );
  if (current !== index) stale.push(join(OUT, 'index.ts'));
  if (stale.length) {
    console.error(
      `out of date: ${stale
        .map((p) => relative(OUT, p))
        .join(
          ', '
        )}\nrun \`yarn workspace @skillsoft/gamut-styles build:tokens\``
    );
    process.exit(1);
  }
  console.log('generated tokens are current');
};

const build = async () => {
  /* Cleared first, so a renamed or removed brand leaves nothing behind. */
  const keep = new Set(BRANDS.map((b) => b.name));
  for (const entry of await readdir(OUT, { withFileTypes: true })) {
    if (!(entry.isDirectory() && keep.has(entry.name))) {
      await rm(join(OUT, entry.name), { recursive: true, force: true });
    }
  }
  for (const brand of BRANDS) {
    await writeBrand(brand, join(OUT, brand.name));
  }
  await writeFile(join(OUT, 'index.ts'), index);
  console.log(`wrote ${BRANDS.map((b) => b.name).join(', ')} to ${OUT}`);
};

const main = async () => {
  if (BRANDS[0] !== DEFAULT_BRAND) {
    throw new Error('BRANDS must start with DEFAULT_BRAND');
  }
  await (process.argv.includes('--check') ? check() : build());
};

main().catch((e) => {
  console.error(e instanceof Error ? e.message : e);
  process.exit(1);
});
